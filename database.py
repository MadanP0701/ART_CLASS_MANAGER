def _upsert_fee_charge(student_id: int, fee_month: str, amount: float) -> int:
    if amount < 0:
        raise ValueError("Charge amount cannot be negative.")
    params = {"sid": student_id, "month": fee_month, "amount": amount}
    with engine.begin() as conn:
        if _is_sqlite():
            conn.execute(text("INSERT INTO fee_charges(student_id,fee_month,amount) VALUES(:sid,:month,:amount) ON CONFLICT(student_id,fee_month) DO UPDATE SET amount=excluded.amount"), params)
            return int(conn.execute(text("SELECT id FROM fee_charges WHERE student_id=:sid AND fee_month=:month"), params).scalar_one())
        return int(conn.execute(text("INSERT INTO fee_charges(student_id,fee_month,amount) VALUES(:sid,:month,:amount) ON CONFLICT(student_id,fee_month) DO UPDATE SET amount=excluded.amount RETURNING id"), params).scalar_one())


def create_fee_charge(student_id: int, fee_month: str, amount: float | None = None) -> int:
    """Create a student's monthly charge using the student's society fee only.

    ``amount`` is retained only for backwards compatibility with older code, but
    it is deliberately ignored. The database/backend always uses the fixed fee
    stored on the student's society. This is the key protection against a
    single student accidentally getting a different fee from the society rate.
    """
    student = _execute(
        """SELECT s.id, s.society_id, so.monthly_fee
           FROM students s JOIN societies so ON so.id=s.society_id
           WHERE s.id=:sid""",
        {"sid": student_id},
    ).mappings().first()
    if not student:
        raise ValueError("Student not found.")
    fixed_fee = round(float(student["monthly_fee"]), 2)
    paid = _execute(
        """SELECT COALESCE(SUM(pa.amount),0)
           FROM payment_allocations pa JOIN fee_charges c ON c.id=pa.charge_id
           WHERE c.student_id=:sid AND c.fee_month=:m""",
        {"sid": student_id, "m": fee_month},
    ).scalar_one()
    if fixed_fee < float(paid):
        raise ValueError(f"Existing payments exceed the fixed society fee for {fee_month}.")
    return _upsert_fee_charge(student_id, fee_month, fixed_fee)


def generate_month_charges(society_id: int, fee_month: str) -> int:
    """Create the society's current monthly fee for every active student who has joined by that month."""
    soc = get_society(society_id)
    created = 0
    for s in get_students(society_id):
        if str(s["joining_date"])[:7] > fee_month:
            continue
        exists = _execute("SELECT id FROM fee_charges WHERE student_id=:sid AND fee_month=:m", {"sid": s["id"], "m": fee_month}).scalar_one_or_none()
        if exists is None:
            create_fee_charge(s["id"], fee_month)
            created += 1
    return created


def _month_range(start: str, end: str):
    y, m = int(start[:4]), int(start[5:7])
    while f"{y:04d}-{m:02d}" <= end:
        yield f"{y:04d}-{m:02d}"
        m += 1
        if m > 12:
            y, m = y + 1, 1


def generate_charges_range(society_id: int, from_month: str, to_month: str) -> int:
    """Create missing monthly charges for every active student, from max(joining month, from_month) up to to_month."""
    soc = get_society(society_id)
    created = 0
    for s in get_students(society_id):
        start = max(str(s["joining_date"])[:7], from_month)
        have = {r["fee_month"] for r in _rows(_execute("SELECT fee_month FROM fee_charges WHERE student_id=:sid", {"sid": s["id"]}))}
        for mth in _month_range(start, to_month):
            if mth not in have:
                create_fee_charge(s["id"], mth)
                created += 1
        apply_credit(s["id"])
    return created


def ensure_current_month_fees(society_id: int, through_month: str | None = None) -> int:
    """Ensure every active student has every monthly charge from joining month through the current month.

    This removes the dangerous manual "generate fees" dependency. Opening the
    society automatically brings its ledger up to date. Existing charges are
    never overwritten.
    """
    if through_month is None:
        through_month = date.today().strftime("%Y-%m")
    return generate_charges_range(society_id, "0001-01", through_month)


def overdue_list(society_id: int):
    return _rows(_execute(
        """SELECT s.name, s.phone, s.active, COUNT(*) AS months_unpaid, MIN(x.fee_month) AS oldest_unpaid, SUM(x.balance) AS pending
           FROM students s JOIN (
               SELECT c.student_id, c.fee_month,
                      c.amount-COALESCE((SELECT SUM(pa.amount) FROM payment_allocations pa WHERE pa.charge_id=c.id),0) AS balance
               FROM fee_charges c) x ON x.student_id=s.id
           WHERE s.society_id=:sid AND x.balance>0.005
           GROUP BY s.id, s.name, s.phone, s.active ORDER BY pending DESC""", {"sid": society_id}))


def apply_credit(student_id: int) -> None:
    """Allocate any unallocated payment money to the oldest unpaid charges."""
    bal_sql = """SELECT c.id, c.amount-COALESCE((SELECT SUM(pa.amount) FROM payment_allocations pa WHERE pa.charge_id=c.id),0) AS balance
                 FROM fee_charges c WHERE c.student_id=:sid ORDER BY c.fee_month, c.id"""
    with engine.begin() as conn:
        pays = conn.execute(text("""SELECT p.id, p.amount-COALESCE((SELECT SUM(pa.amount) FROM payment_allocations pa WHERE pa.payment_id=p.id),0) AS free
                                    FROM payments p WHERE p.student_id=:sid ORDER BY p.payment_date, p.id"""), {"sid": student_id}).mappings().all()
        for p in pays:
            free = round(float(p["free"]), 2)
            for c in conn.execute(text(bal_sql), {"sid": student_id}).mappings().all():
                if free <= 0:
                    break
                alloc = min(free, round(float(c["balance"]), 2))
                if alloc <= 0:
                    continue
                prm = {"pid": p["id"], "cid": c["id"], "a": alloc}
                done = conn.execute(text("UPDATE payment_allocations SET amount=amount+:a WHERE payment_id=:pid AND charge_id=:cid"), prm).rowcount
                if not done:
                    conn.execute(text("INSERT INTO payment_allocations(payment_id,charge_id,amount) VALUES(:pid,:cid,:a)"), prm)
                free = round(free - alloc, 2)


def delete_payment(payment_id: int) -> None:
    row = _execute("SELECT student_id FROM payments WHERE id=:id", {"id": payment_id}).mappings().first()
    if not row:
        return
    with engine.begin() as conn:
        conn.execute(text("DELETE FROM payment_allocations WHERE payment_id=:id"), {"id": payment_id})
        conn.execute(text("DELETE FROM payments WHERE id=:id"), {"id": payment_id})
    apply_credit(int(row["student_id"]))


def delete_student_permanently(student_id: int) -> None:
    """All-or-nothing: either everything about the student is removed, or nothing is."""
    p = {"sid": student_id}
    with engine.begin() as conn:
        conn.execute(text("DELETE FROM payment_allocations WHERE payment_id IN (SELECT id FROM payments WHERE student_id=:sid)"), p)
        conn.execute(text("DELETE FROM payment_allocations WHERE charge_id IN (SELECT id FROM fee_charges WHERE student_id=:sid)"), p)
        for t in ("attendance", "payments", "fee_charges"):
            conn.execute(text(f"DELETE FROM {t} WHERE student_id=:sid"), p)
        conn.execute(text("DELETE FROM students WHERE id=:sid"), p)


