def _secret(name: str, default: str = "") -> str:
    value = os.getenv(name, "").strip()
    if value:
        return value
    try:
        import streamlit as st
        return str(st.secrets.get(name, default)).strip()
    except Exception:
        return default


def _database_url() -> str:
    """
    Production rule: the app MUST use a remote PostgreSQL database.
    SQLite is allowed only when ALLOW_LOCAL_SQLITE=1 is explicitly set for
    local development. This prevents a Streamlit deployment from silently
    writing business data to an ephemeral local .db file.
    """
    url = _secret("DATABASE_URL")
    if url:
        return url

    if _secret("ALLOW_LOCAL_SQLITE", "").lower() in {"1", "true", "yes"}:
        return f"sqlite:///{LOCAL_DB.as_posix()}"

    raise RuntimeError(
        "DATABASE_URL is not configured. For the hosted app, add a persistent "
        "PostgreSQL DATABASE_URL to Streamlit Secrets. Local SQLite is disabled "
        "by default so business data cannot disappear when the app restarts."
    )


def _is_sqlite() -> bool:
    return _database_url().lower().startswith("sqlite:")


_URL = _database_url()
if _URL.lower().startswith("sqlite:"):
    _connect_args = {"check_same_thread": False}
    engine: Engine = create_engine(_URL, future=True, pool_pre_ping=True, connect_args=_connect_args)
else:
    # Small pool is intentional for Streamlit + hosted PostgreSQL. It avoids
    # opening a new database connection on every Streamlit rerun.
    #
    # prepare_threshold=0 is compatible with Supabase pooler connections,
    # including transaction-pooling mode, where prepared statements are not
    # supported.
    _connect_args = {"sslmode": "require", "prepare_threshold": 0}
    engine: Engine = create_engine(
        _URL,
        future=True,
        pool_pre_ping=True,
        pool_size=3,
        max_overflow=2,
        pool_recycle=1800,
        connect_args=_connect_args,
    )


def database_mode() -> str:
    return "local SQLite" if _is_sqlite() else "remote PostgreSQL"


def database_is_remote() -> bool:
    return not _is_sqlite()


