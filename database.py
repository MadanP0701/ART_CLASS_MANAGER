def _execute(sql: str, params: dict[str, Any] | None = None):
    with engine.begin() as conn:
        return conn.execute(text(sql), params or {})


def init_db() -> None:
    # PostgreSQL and SQLite share this schema. Internal numeric IDs are never shown to users.
    statements = [
        """CREATE TABLE IF NOT EXISTS societies (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name VARCHAR(200) NOT NULL UNIQUE,
            monthly_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
            notes TEXT DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS students (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            society_id INTEGER NOT NULL REFERENCES societies(id),
            name VARCHAR(200) NOT NULL,
            parent_name VARCHAR(200) DEFAULT '',
            phone VARCHAR(40) DEFAULT '',
            joining_date DATE NOT NULL,
            active BOOLEAN NOT NULL DEFAULT TRUE,
            notes TEXT DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS attendance (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id INTEGER NOT NULL REFERENCES students(id),
            attendance_date DATE NOT NULL,
            present BOOLEAN NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(student_id, attendance_date)
        )""",
        """CREATE TABLE IF NOT EXISTS fee_charges (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id INTEGER NOT NULL REFERENCES students(id),
            fee_month VARCHAR(7) NOT NULL,
            amount NUMERIC(12,2) NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(student_id, fee_month)
        )""",
        """CREATE TABLE IF NOT EXISTS payments (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id INTEGER NOT NULL REFERENCES students(id),
            payment_date DATE NOT NULL,
            amount NUMERIC(12,2) NOT NULL,
            method VARCHAR(50) DEFAULT 'Cash',
            reference VARCHAR(200) DEFAULT '',
            notes TEXT DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS payment_allocations (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            payment_id INTEGER NOT NULL REFERENCES payments(id),
            charge_id INTEGER NOT NULL REFERENCES fee_charges(id),
            amount NUMERIC(12,2) NOT NULL,
            UNIQUE(payment_id, charge_id)
        )""",
    ]

    if _is_sqlite():
        # SQLite does not support GENERATED BY DEFAULT AS IDENTITY.
        statements = [s.replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT") for s in statements]

    with engine.begin() as conn:
        if _is_sqlite():
            conn.execute(text("PRAGMA foreign_keys = ON"))
        for sql in statements:
            conn.execute(text(sql))
        indexes = [
            "CREATE INDEX IF NOT EXISTS idx_students_society ON students(society_id)",
            "CREATE INDEX IF NOT EXISTS idx_attendance_student_date ON attendance(student_id, attendance_date)",
            "CREATE INDEX IF NOT EXISTS idx_charges_student_month ON fee_charges(student_id, fee_month)",
            "CREATE INDEX IF NOT EXISTS idx_payments_student_date ON payments(student_id, payment_date)",
        ]
        for sql in indexes:
            conn.execute(text(sql))

        # Hard backend invariant: a society's monthly student fee is fixed at creation.
        # The UI also hides editing, but the trigger prevents accidental changes from
        # any future code path or direct SQL connection.
        if _is_sqlite():
            conn.execute(text("""
                CREATE TRIGGER IF NOT EXISTS prevent_society_fee_change
                BEFORE UPDATE OF monthly_fee ON societies
                WHEN ROUND(OLD.monthly_fee, 2) <> ROUND(NEW.monthly_fee, 2)
                BEGIN
                    SELECT RAISE(ABORT, 'A society monthly fee is fixed after creation.');
                END
            """))
        else:
            conn.execute(text("""
                CREATE OR REPLACE FUNCTION prevent_society_fee_change_fn()
                RETURNS trigger AS $$
                BEGIN
                    IF ROUND(OLD.monthly_fee, 2) <> ROUND(NEW.monthly_fee, 2) THEN
                        RAISE EXCEPTION 'A society monthly fee is fixed after creation.';
                    END IF;
                    RETURN NEW;
                END;
                $$ LANGUAGE plpgsql;
            """))
            conn.execute(text("DROP TRIGGER IF EXISTS prevent_society_fee_change ON societies"))
            conn.execute(text("""
                CREATE TRIGGER prevent_society_fee_change
                BEFORE UPDATE OF monthly_fee ON societies
                FOR EACH ROW EXECUTE FUNCTION prevent_society_fee_change_fn()
            """))


def _rows(result):
    return [dict(r._mapping) for r in result]


def create_society(name: str, monthly_fee: float, notes: str = "") -> int:
    name = name.strip()
    if not name:
        raise ValueError("Society name is required.")
    if monthly_fee < 0:
        raise ValueError("Monthly fee cannot be negative.")
    with engine.begin() as conn:
        if _is_sqlite():
            conn.execute(text("INSERT INTO societies(name, monthly_fee, notes) VALUES (:name, :fee, :notes)"), {"name": name, "fee": monthly_fee, "notes": notes.strip()})
            return int(conn.execute(text("SELECT last_insert_rowid()" )).scalar_one())
        return int(conn.execute(text("INSERT INTO societies(name, monthly_fee, notes) VALUES (:name, :fee, :notes) RETURNING id"), {"name": name, "fee": monthly_fee, "notes": notes.strip()}).scalar_one())


def update_society(society_id: int, name: str, notes: str = "") -> None:
    """Update society details without ever changing its fixed monthly student fee.

    The monthly fee is an invariant of a society. It is set when the society is
    created and cannot be changed through the application. This prevents a fee
    change from silently altering future student charges.
    """
    if not name.strip():
        raise ValueError("Society name is required.")
    _execute(
        "UPDATE societies SET name=:name, notes=:notes, updated_at=CURRENT_TIMESTAMP WHERE id=:id",
        {"id": society_id, "name": name.strip(), "notes": notes.strip()},
    )


def delete_society(society_id: int) -> None:
    row = _execute("SELECT COUNT(*) FROM students WHERE society_id=:id", {"id": society_id}).scalar_one()
    if int(row) > 0:
        raise ValueError("Society cannot be deleted while it has students. Deactivate students instead.")
    _execute("DELETE FROM societies WHERE id=:id", {"id": society_id})


