def backup_local_db(keep: int = 30) -> None:
    """Consistent snapshot of the local SQLite file (no-op on PostgreSQL, where the host keeps backups)."""
    if not _is_sqlite() or not LOCAL_DB.exists():
        return
    folder = BASE_DIR / "backups"
    folder.mkdir(exist_ok=True)
    target = folder / f"art_class_{datetime.now().strftime('%Y%m%d_%H%M%S')}.db"
    src, dst = sqlite3.connect(LOCAL_DB), sqlite3.connect(target)
    try:
        src.backup(dst)
    finally:
        dst.close(); src.close()
    for old in sorted(folder.glob("art_class_*.db"))[:-keep]:
        old.unlink()


